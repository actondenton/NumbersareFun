import {
    createNumber1SlowdownBoot,
    createNumber1CheapenBoot,
    createNumber1SpeedUpgradeBoot
} from "./modules/number1/upgrades.js";
import { createNumber1TimeWarpBoot } from "./modules/number1/time-warp.js";

/**
 * Wires slowdown, cheapen, speed upgrade boots and Number 1 time-warp boot (legacy orchestration).
 * Mutates caller-owned state via getters/setters in `deps`.
 *
 * @param {object} deps
 */
export function wireNumber1SlowdownCheapenSpeedAndTimeWarpBoots(deps) {
    const {
        getBlackHolePhase,
        getUnlockedHands,
        getHandEarnings,
        getSlowdownLevel,
        getSlowdownBonusLevel,
        getSlowdownAutoBuyCountdownByHand,
        setSlowdownAutoBuyCountdown,
        getMaxSlowdownLevelCap,
        getSlowdownUpgradeCost,
        isSlowdownUnlocked,
        getDevSlowdownAutobuyOn,
        ascensionAutobuyIncludesSlowdown,
        getAutoBuyUnlocked,
        getAutoBuyEnabledByHand,
        setHandEarningBalance,
        markMeaningfulProgress,
        markAutobuyDeferredTotalsPending,
        refreshTotalFromHandEarnings,
        getIncrementalCountEl,
        formatCount,
        getTotalChanges,
        addToLog,
        setSlowdownBaseLevel,
        resetSpeedLevelForCompaction,
        getHands,
        getSpeedRowRefs,
        sprayConfettiFrom,
        setUpgradeTooltipText,
        setUpgradeButtonProgress,
        formatUpgradeAffordEtaLine,
        flashSpeedAutobuyToast,
        setBatchedUpgradeUiFlush,
        updateSpeedUpgradeUI,
        updateRateDisplay,
        updateHandUpgradeScrollHint,
        getAutoBuyDelaySeconds,
        getSlowdownUnlockLogged,
        setSlowdownUnlockLogged,
        getCheapenLevel,
        getCheapenBonusLevel,
        getCheapenSectionUnlocked,
        setCheapenSectionUnlocked,
        getCheapenAutoBuyCountdownByHand,
        setCheapenAutoBuyCountdown,
        getMaxCheapenLevel,
        getCheapenUpgradeCost,
        getDevCheapenAutobuyOn,
        ascensionAutobuyIncludesCheapen,
        getCheapenEffectText,
        setCheapenBaseLevel,
        ensureSpeedRows,
        getSpeedLevel,
        getUpgradeCost,
        incrementSpeedLevel,
        restartAllHandTimers,
        setSpeedAutobuyCountdown,
        getAutoBuyCountdownSecondsByHand,
        computeAscensionGrantTotals,
        getHandPerHandRawCps,
        getTimeWarpComboMultiplier,
        getTurboCountMultiplier,
        getNumber1BlackHoleProductionMult,
        scheduleObjectiveDomFlush,
        updateMilestoneUI,
        scheduleHandUpgradeScrollHintUpdate,
        handScrollHintHasUpgradeReason,
        getNumber1HasAscended,
        getAscensionPendingBonusEssence,
        setAscensionPendingBonusEssence,
        refreshOverviewAndAscensionHubLiveIfOpen,
        autosaveNow,
        getTimeWarpAuraActiveByHand,
        setTimeWarpAuraActiveByHand,
        getTimeWarpAuraAppearedAtMsByHand,
        setTimeWarpAuraAppearedAtMsByHand,
        getTimeWarpNextSpawnInSec,
        setTimeWarpNextSpawnInSec,
        getTimeWarpUnlockLogged,
        setTimeWarpUnlockLogged,
        flushAutobuyDeferredTotalsIfAny,
        scrollHintTimeWarpApi
    } = deps;

    const n1UpgradeCrossRefresh = {
        updateCheapenUpgradeUI() {},
        updateSlowdownUpgradeUI() {}
    };
    const number1SlowdownBoot = createNumber1SlowdownBoot({
        getBlackHolePhase,
        getUnlockedHands,
        getHandEarnings,
        getSlowdownLevel,
        getSlowdownBonusLevel,
        getSlowdownAutoBuyCountdownByHand,
        setSlowdownAutoBuyCountdown,
        getMaxSlowdownLevelCap,
        getSlowdownUpgradeCost,
        isSlowdownUnlocked,
        devSlowdownAutobuyOn: getDevSlowdownAutobuyOn,
        ascensionAutobuyIncludesSlowdown,
        getAutoBuyUnlocked,
        getAutoBuyEnabledByHand,
        setHandEarningBalance,
        markMeaningfulProgress,
        markAutobuyDeferredTotalsPending,
        refreshTotalFromHandEarnings,
        getIncrementalCountEl,
        formatCount,
        getTotalChanges,
        addToLog,
        setSlowdownBaseLevel,
        resetSpeedLevelForCompaction,
        getHands,
        getSpeedRowRefs,
        sprayConfettiFrom,
        setUpgradeTooltipText,
        setUpgradeButtonProgress,
        formatUpgradeAffordEtaLine,
        flashSpeedAutobuyToast,
        setBatchedUpgradeUiFlush,
        updateSpeedUpgradeUI,
        updateCheapenUpgradeUI: () => n1UpgradeCrossRefresh.updateCheapenUpgradeUI(),
        updateRateDisplay,
        updateHandUpgradeScrollHint,
        getAutoBuyDelaySeconds,
        onSlowdownUnlockedFirstUi: () => {
            if (isSlowdownUnlocked() && !getSlowdownUnlockLogged()) {
                setSlowdownUnlockLogged(true);
                addToLog("Compaction unlocked (all hands).", "milestone");
            }
        }

    });
    const number1CheapenBoot = createNumber1CheapenBoot({
        getBlackHolePhase,
        getUnlockedHands,
        getHandEarnings,
        getCheapenLevel,
        getCheapenBonusLevel,
        getCheapenSectionUnlocked,
        setCheapenSectionUnlocked,
        getCheapenAutoBuyCountdownByHand,
        setCheapenAutoBuyCountdown,
        getMaxCheapenLevel,
        getCheapenUpgradeCost,
        devCheapenAutobuyOn: getDevCheapenAutobuyOn,
        ascensionAutobuyIncludesCheapen,
        getAutoBuyUnlocked,
        getAutoBuyEnabledByHand,
        setHandEarningBalance,
        markMeaningfulProgress,
        markAutobuyDeferredTotalsPending,
        refreshTotalFromHandEarnings,
        getIncrementalCountEl,
        formatCount,
        getTotalChanges,
        addToLog,
        getCheapenEffectText,
        setCheapenBaseLevel,
        getSpeedRowRefs,
        sprayConfettiFrom,
        setUpgradeTooltipText,
        setUpgradeButtonProgress,
        formatUpgradeAffordEtaLine,
        flashSpeedAutobuyToast,
        setBatchedUpgradeUiFlush,
        updateSpeedUpgradeUI,
        updateSlowdownUpgradeUI: () => n1UpgradeCrossRefresh.updateSlowdownUpgradeUI(),
        updateRateDisplay,
        ensureSpeedRows,
        updateHandUpgradeScrollHint,
        getAutoBuyDelaySeconds
    });
    const number1SpeedUpgradeBoot = createNumber1SpeedUpgradeBoot({
        getBlackHolePhase,
        getUnlockedHands,
        getSpeedLevel,
        getCheapenLevel,
        getSlowdownLevel,
        getUpgradeCost,
        getHandEarnings,
        setHandEarningBalance,
        markMeaningfulProgress,
        markAutobuyDeferredTotalsPending,
        refreshTotalFromHandEarnings,
        incrementSpeedLevel,
        getHands,
        addToLog,
        getIncrementalCountEl,
        formatCount,
        getTotalChanges,
        restartAllHandTimers,
        getAutoBuyUnlocked,
        setSpeedAutobuyCountdown,
        getAutoBuyEnabledByHand,
        getAutoBuyCountdownSecondsByHand,
        getAutoBuyDelaySeconds,
        getSpeedRowRefs,
        sprayConfettiFrom,
        setBatchedUpgradeUiFlush,
        updateSpeedUpgradeUI,
        updateCheapenUpgradeUI: () => n1UpgradeCrossRefresh.updateCheapenUpgradeUI(),
        updateSlowdownUpgradeUI: () => n1UpgradeCrossRefresh.updateSlowdownUpgradeUI(),
        updateRateDisplay,
        flashSpeedAutobuyToast,
        getMaxCheapenLevel,
        getCheapenUpgradeCost,
        getSlowdownUpgradeCost,
        getMaxSlowdownLevelCap,
        isSlowdownUnlocked,
        buyCheapenUpgradeForHand: number1CheapenBoot.buyCheapenUpgradeForHand,
        buySlowdownUpgradeForHand: number1SlowdownBoot.buySlowdownUpgradeForHand,
        flushAutobuyDeferredTotalsIfAny
    });
    n1UpgradeCrossRefresh.updateCheapenUpgradeUI = () => {
        number1CheapenBoot.updateCheapenUpgradeUI();
    };
    n1UpgradeCrossRefresh.updateSlowdownUpgradeUI = () => {
        number1SlowdownBoot.updateSlowdownUpgradeUI();
    };

    const number1TimeWarpBoot = createNumber1TimeWarpBoot({
        getTotalChanges,
        getUnlockedHands,
        getSpeedRowRefs,
        getHandEarnings,
        setHandEarningBalance,
        getTimeWarpAuraActiveByHand,
        setTimeWarpAuraActiveByHand,
        getTimeWarpAuraAppearedAtMsByHand,
        setTimeWarpAuraAppearedAtMsByHand,
        getTimeWarpNextSpawnInSec,
        setTimeWarpNextSpawnInSec,
        getTimeWarpUnlockLogged,
        setTimeWarpUnlockLogged,
        computeAscensionGrantTotals,
        getHandPerHandRawCps,
        getTimeWarpComboMultiplier,
        getTurboCountMultiplier,
        getNumber1BlackHoleProductionMult,
        getIncrementalCountEl,
        formatCount,
        refreshTotalFromHandEarnings,
        updateObjectives: scheduleObjectiveDomFlush,
        updateSpeedUpgradeUI,
        updateCheapenUpgradeUI: number1CheapenBoot.updateCheapenUpgradeUI,
        updateSlowdownUpgradeUI: number1SlowdownBoot.updateSlowdownUpgradeUI,
        updateRateDisplay,
        updateMilestoneUI,
        addToLog,
        markMeaningfulProgress,
        scheduleHandUpgradeScrollHintUpdate,
        handScrollHintHasUpgradeReason,
        getNumber1HasAscended,
        getAscensionPendingBonusEssence,
        setAscensionPendingBonusEssence,
        refreshOverviewAndAscensionHubLiveIfOpen,
        autosaveNow,
        getSpeedLevel,
        getCheapenLevel,
        getSlowdownLevel,
        getMaxCheapenLevel,
        getCheapenUpgradeCost,
        getUpgradeCost,
        getSlowdownUpgradeCost,
        getMaxSlowdownLevelCap,
        isSlowdownUnlocked,
        buyCheapenUpgradeForHand: number1CheapenBoot.buyCheapenUpgradeForHand,
        buySpeedUpgradeForHand: number1SpeedUpgradeBoot.buySpeedUpgradeForHand,
        buySlowdownUpgradeForHand: number1SlowdownBoot.buySlowdownUpgradeForHand,
        flushAutobuyDeferredTotalsIfAny
    });
    const {
        handHasActiveTimeWarpAura,
        handContributesTimeWarpPriority,
        handContributesToScrollHint,
        ensureTimeWarpArrays,
        getWarpPotencyMaxTiersEffective,
        getWarpPotencyTierForHandNow,
        getWarpPotencyMultiplierForHandNow,
        scheduleNextTimeWarpSpawn,
        getTimeWarpGrantForHand,
        applyTimeWarpGrant,
        tryGrantAscensionBonusEssenceFromWarp,
        applyTimeWarpOverflowToAllHands,
        applyTimeWarpManualAutoBuyAssistForHand,
        playTimeWarpScreenEffect,
        activateTimeWarpAuraForHand,
        updateTimeWarpSystem,
        getAscensionComboTimeWarpDelayReductionPerTriggerSec,
        applyAscensionComboTimeWarpDelayReduction
    } = number1TimeWarpBoot;
    Object.assign(scrollHintTimeWarpApi, {
        handContributesToScrollHint,
        handContributesTimeWarpPriority,
        handHasActiveTimeWarpAura
    });
    number1TimeWarpBoot.wireAfterWarpAssist(() => {
        setBatchedUpgradeUiFlush(false);
        updateSpeedUpgradeUI();
        number1CheapenBoot.updateCheapenUpgradeUI();
        number1SlowdownBoot.updateSlowdownUpgradeUI();
        updateRateDisplay();
        number1TimeWarpBoot.updateTimeWarpAuraUI();
    });

    return {
        number1SlowdownBoot,
        number1CheapenBoot,
        number1SpeedUpgradeBoot,
        number1TimeWarpBoot,
        handHasActiveTimeWarpAura,
        handContributesTimeWarpPriority,
        handContributesToScrollHint,
        ensureTimeWarpArrays,
        getWarpPotencyMaxTiersEffective,
        getWarpPotencyTierForHandNow,
        getWarpPotencyMultiplierForHandNow,
        scheduleNextTimeWarpSpawn,
        getTimeWarpGrantForHand,
        applyTimeWarpGrant,
        tryGrantAscensionBonusEssenceFromWarp,
        applyTimeWarpOverflowToAllHands,
        applyTimeWarpManualAutoBuyAssistForHand,
        playTimeWarpScreenEffect,
        activateTimeWarpAuraForHand,
        updateTimeWarpSystem,
        getAscensionComboTimeWarpDelayReductionPerTriggerSec,
        applyAscensionComboTimeWarpDelayReduction,
        updateTimeWarpAuraUI: number1TimeWarpBoot.updateTimeWarpAuraUI
    };
}
